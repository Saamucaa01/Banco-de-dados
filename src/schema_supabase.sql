BEGIN;


CREATE TABLE IF NOT EXISTS public.monitorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina TEXT NOT NULL CHECK (char_length(btrim(disciplina)) > 0),
    monitor TEXT NOT NULL CHECK (char_length(btrim(monitor)) > 0),
    dia_semana SMALLINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    local TEXT NOT NULL CHECK (char_length(btrim(local)) > 0),
    vagas INTEGER NOT NULL,
    CONSTRAINT ck_monitorias_dia_semana_valido CHECK (dia_semana BETWEEN 0 AND 5),
    CONSTRAINT ck_monitorias_vagas_positivas CHECK (vagas > 0),
    CONSTRAINT ck_monitorias_horario_valido CHECK (hora_fim > hora_inicio)
);


CREATE TABLE IF NOT EXISTS public.agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitoria_id BIGINT NOT NULL,
    aluno_matricula TEXT NOT NULL CHECK (char_length(btrim(aluno_matricula)) > 0),
    aluno_nome TEXT NOT NULL CHECK (char_length(btrim(aluno_nome)) > 0),
    data DATE NOT NULL,
    assunto TEXT NOT NULL CHECK (char_length(btrim(assunto)) > 0),
    situacao TEXT NOT NULL DEFAULT 'solicitado',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_agendamentos_monitoria
        FOREIGN KEY (monitoria_id)
        REFERENCES public.monitorias (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT ck_agendamentos_situacao_valida
        CHECK (situacao IN ('solicitado', 'confirmado', 'realizado', 'cancelado'))
);


CREATE TABLE IF NOT EXISTS public.historico_situacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT NOT NULL,
    situacao_anterior TEXT NULL,
    situacao_nova TEXT NOT NULL,
    registrada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_historico_agendamento
        FOREIGN KEY (agendamento_id)
        REFERENCES public.agendamentos (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT ck_historico_situacao_anterior_valida
        CHECK (
            situacao_anterior IS NULL
            OR situacao_anterior IN ('solicitado', 'confirmado', 'realizado', 'cancelado')
        ),
    CONSTRAINT ck_historico_situacao_nova_valida
        CHECK (situacao_nova IN ('solicitado', 'confirmado', 'realizado', 'cancelado'))
);


CREATE INDEX IF NOT EXISTS idx_agendamentos_monitoria_data
    ON public.agendamentos (monitoria_id, data);

CREATE INDEX IF NOT EXISTS idx_agendamentos_aluno_matricula
    ON public.agendamentos (aluno_matricula);

CREATE INDEX IF NOT EXISTS idx_agendamentos_situacao
    ON public.agendamentos (situacao);

CREATE INDEX IF NOT EXISTS idx_historico_agendamento_id
    ON public.historico_situacoes (agendamento_id, registrada_em);

-- Impede no banco que o mesmo aluno tenha dois agendamentos ativos
-- ('solicitado' ou 'confirmado') para a mesma monitoria e data.
CREATE UNIQUE INDEX IF NOT EXISTS uq_agendamentos_aluno_monitoria_data_ativo
    ON public.agendamentos (aluno_matricula, monitoria_id, data)
    WHERE situacao IN ('solicitado', 'confirmado');


CREATE OR REPLACE FUNCTION public.adicionar_agendamento_com_historico(
    p_monitoria_id BIGINT,
    p_aluno_matricula TEXT,
    p_aluno_nome TEXT,
    p_data DATE,
    p_assunto TEXT,
    p_situacao TEXT DEFAULT 'solicitado',
    p_criado_em TIMESTAMPTZ DEFAULT NULL,
    p_situacao_anterior TEXT DEFAULT NULL,
    p_situacao_nova TEXT DEFAULT NULL,
    p_registrada_em TIMESTAMPTZ DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_agendamento public.agendamentos%ROWTYPE;
    v_historico public.historico_situacoes%ROWTYPE;
    v_criado_em TIMESTAMPTZ := COALESCE(p_criado_em, now());
    v_registrada_em TIMESTAMPTZ := COALESCE(p_registrada_em, v_criado_em);
    v_situacao_nova TEXT := COALESCE(p_situacao_nova, p_situacao);
    v_vagas INTEGER;
    v_ativos INTEGER;
BEGIN
    IF v_situacao_nova IS DISTINCT FROM p_situacao THEN
        RAISE EXCEPTION 'Inconsistência: situacao do agendamento (%) difere de situacao_nova do histórico (%)',
            p_situacao, v_situacao_nova
            USING ERRCODE = '22023';
    END IF;


    SELECT vagas
      INTO v_vagas
      FROM public.monitorias
     WHERE id = p_monitoria_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Monitoria com ID % não encontrada.', p_monitoria_id
            USING ERRCODE = 'P0002';
    END IF;


    IF p_situacao IN ('solicitado', 'confirmado') THEN
        SELECT count(*)
          INTO v_ativos
          FROM public.agendamentos
         WHERE monitoria_id = p_monitoria_id
           AND data = p_data
           AND situacao IN ('solicitado', 'confirmado');


        IF v_ativos >= v_vagas AND NOT EXISTS (
            SELECT 1
              FROM public.agendamentos
             WHERE monitoria_id = p_monitoria_id
               AND data = p_data
               AND aluno_matricula = p_aluno_matricula
               AND situacao IN ('solicitado', 'confirmado')
        ) THEN
            RAISE EXCEPTION 'Monitoria % lotada em %: % de % vagas ocupadas.',
                p_monitoria_id, p_data, v_ativos, v_vagas
                USING ERRCODE = 'CC001';
        END IF;
    END IF;

    INSERT INTO public.agendamentos (
        monitoria_id, aluno_matricula, aluno_nome, data, assunto, situacao, criado_em
    )
    VALUES (
        p_monitoria_id, p_aluno_matricula, p_aluno_nome, p_data, p_assunto,
        p_situacao, v_criado_em
    )
    RETURNING * INTO v_agendamento;

    INSERT INTO public.historico_situacoes (
        agendamento_id, situacao_anterior, situacao_nova, registrada_em
    )
    VALUES (
        v_agendamento.id, p_situacao_anterior, v_situacao_nova, v_registrada_em
    )
    RETURNING * INTO v_historico;

    RETURN jsonb_build_object(
        'agendamento', to_jsonb(v_agendamento),
        'historico', to_jsonb(v_historico)
    );
END;
$$;


CREATE OR REPLACE FUNCTION public.registrar_mudanca_situacao(
    p_agendamento_id BIGINT,
    p_situacao_anterior TEXT,
    p_situacao_nova TEXT,
    p_registrada_em TIMESTAMPTZ DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_agendamento public.agendamentos%ROWTYPE;
    v_historico public.historico_situacoes%ROWTYPE;
    v_situacao_atual TEXT;
    v_registrada_em TIMESTAMPTZ := COALESCE(p_registrada_em, now());
BEGIN
    SELECT situacao
      INTO v_situacao_atual
      FROM public.agendamentos
     WHERE id = p_agendamento_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Agendamento com ID % não encontrado.', p_agendamento_id
            USING ERRCODE = 'P0002';
    END IF;

    IF p_situacao_anterior IS NOT NULL
       AND v_situacao_atual IS DISTINCT FROM p_situacao_anterior THEN
        RAISE EXCEPTION 'Conflito de situação no agendamento %: esperada %, atual %.',
            p_agendamento_id, p_situacao_anterior, v_situacao_atual
            USING ERRCODE = '40001';
    END IF;

    UPDATE public.agendamentos
       SET situacao = p_situacao_nova
     WHERE id = p_agendamento_id
    RETURNING * INTO v_agendamento;

    INSERT INTO public.historico_situacoes (
        agendamento_id, situacao_anterior, situacao_nova, registrada_em
    )
    VALUES (
        p_agendamento_id,
        COALESCE(p_situacao_anterior, v_situacao_atual),
        p_situacao_nova,
        v_registrada_em
    )
    RETURNING * INTO v_historico;

    RETURN jsonb_build_object(
        'agendamento', to_jsonb(v_agendamento),
        'historico', to_jsonb(v_historico)
    );
END;
$$;


