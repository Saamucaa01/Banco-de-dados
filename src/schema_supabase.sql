CREATE POLICY pol_monitorias_leitura ON public.monitorias
    FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS pol_monitorias_cadastro ON public.monitorias;
CREATE POLICY pol_monitorias_cadastro ON public.monitorias
    FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS pol_agendamentos_leitura ON public.agendamentos;
CREATE POLICY pol_agendamentos_leitura ON public.agendamentos
    FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS pol_historico_leitura ON public.historico_situacoes;
CREATE POLICY pol_historico_leitura ON public.historico_situacoes
    FOR SELECT TO anon, authenticated USING (true);

GRANT USAGE ON SCHEMA public TO anon, authenticated;

